Raqueta::Raqueta()
{
	velocidad.x=0;
	velocidad.y=0;
    pos.x=0;
	pos.y=0;
}

Raqueta::~Raqueta()
{

}

void Raqueta::Mueve(float t)
{
    pos = pos + velocidad*t;
}
